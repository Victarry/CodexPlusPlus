// 从内置分片生成兼容拓展，用于不重启现有管理器的部署；新内置版本自动接管。
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const source = await readFile(path.join(root, "assets/inject/renderer-inject/88-side-chat-save.js"), "utf8");
const output = process.argv[2] || path.join(root, "dist/side-chat-save.user.js");
const body = `// Generated by scripts/build-side-chat-save-extension.mjs; edit the builtin fragment.\n(() => {
  const api = window.codexPlus;
  if (!api || window.__codexPlusSideChatSaveState?.builtinVersion >= 2) return;
  window.__codexPlusSideChatSaveState?.extensionCleanup?.();
  const codexSideSaveExtensionMode = true;
  const codexPlusBackendSettings = new Proxy({}, {get: (_, key) => window.__codexPlusSettings?.[key]});
  const showToast = (message, options) => api.toast(message, options);
${source}
  let timer;
  const scan = () => {
    clearTimeout(timer);
    if (document.hidden) return;
    timer = setTimeout(syncCodexSideChatSaveButtons, 150);
  };
  const observer = new MutationObserver((mutations) => {
    if (mutations.some((mutation) => {
      if (mutation.target.closest?.('[data-codex-plus-ext]')) return false;
      const nodes = [...mutation.addedNodes, ...mutation.removedNodes].filter(node => node.nodeType === 1);
      if (nodes.length && nodes.every(node => node.matches?.('[data-codex-plus-ext]'))) return false;
      return mutation.target.closest?.('[role="tabpanel"]') || nodes.some(node => node.matches?.('[data-tab-id]') || node.querySelector?.('[data-tab-id]'));
    })) scan();
  });
  observer.observe(document.body, {childList: true, subtree: true});
  document.addEventListener('visibilitychange', scan);
  const cleanup = () => {
    clearTimeout(timer); observer.disconnect(); document.removeEventListener('visibilitychange', scan);
    document.querySelectorAll('[data-codex-plus-side-save]').forEach(node => node.remove());
    if (codexSideSaveState.extensionCleanup === cleanup) delete codexSideSaveState.extensionCleanup;
  };
  codexSideSaveState.extensionCleanup = cleanup;
  api.onCleanup(cleanup);
  scan();
})();\n`;
new Function(body);
await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, body, { mode: 0o600 });
console.log(`已生成 ${output}`);
